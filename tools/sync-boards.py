#!/usr/bin/env python3
"""tools/sync-boards.py: write the board files (boards/*.conf) into synodeb-setup.sh.

synodeb-setup.sh must stay a single downloadable file, so it carries a copy of the board data
between the "### boards begin" and "### boards end" lines, as the model_profile function. This
script regenerates that block, and copies the board files into the synology package
(pkg/synodeb/usr/share/synodeb/boards, read by /usr/lib/synodeb/board on the installed
system). CI runs it with --check and fails if a copy is out of date.

  tools/sync-boards.py           rewrite the block in synodeb-setup.sh
  tools/sync-boards.py --check   exit 1 if the block differs from boards/*.conf
"""
import pathlib
import re
import shlex
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SETUP = ROOT / "synodeb-setup.sh"
PKG_BOARDS = ROOT / "pkg/synodeb/usr/share/synodeb/boards"
BEGIN = "### boards begin (generated by tools/sync-boards.py from boards/*.conf: do not edit)"
END = "### boards end"
KEYS = ("MODEL", "PLATFORM", "TIER", "BAYS", "CONSOLE", "DOM_FAT_ID", "DOM_EXT_UUID",
        "DOM_P1_MIN", "DOM_P2_MIN")
TIERS = ("supported", "community", "wip")


def load(path):
    """KEY="value" lines only (comments and blank lines allowed), every key of KEYS once."""
    board = {}
    for n, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.fullmatch(r'([A-Z][A-Z0-9_]*)="([^"$`\\]*)"(\s+#.*)?', line)
        if not m:
            sys.exit(f"{path}:{n}: not a KEY=\"value\" line")
        key, value = m.group(1), m.group(2)
        if key not in KEYS:
            sys.exit(f"{path}:{n}: unknown key {key}")
        if key in board:
            sys.exit(f"{path}:{n}: {key} given twice")
        board[key] = value
    missing = [k for k in KEYS if k not in board]
    if missing:
        sys.exit(f"{path}: missing {', '.join(missing)}")
    if board["TIER"] not in TIERS:
        sys.exit(f"{path}: TIER must be one of {', '.join(TIERS)}")
    if not re.fullmatch(r"[0-9A-F]{4}-[0-9A-F]{4}", board["DOM_FAT_ID"]):
        sys.exit(f"{path}: DOM_FAT_ID is not XXXX-XXXX")
    if not re.fullmatch(r"[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}", board["DOM_EXT_UUID"]):
        sys.exit(f"{path}: DOM_EXT_UUID is not a UUID")
    for k in ("BAYS", "DOM_P1_MIN", "DOM_P2_MIN"):
        if not board[k].isdigit():
            sys.exit(f"{path}: {k} is not a number")
    return board


def fat_bytes(fat_id):
    """10EE-589C -> "9c 58 ee 10" (the volume id as stored, little endian)."""
    v = int(fat_id.replace("-", ""), 16)
    return " ".join(f"{b:02x}" for b in v.to_bytes(4, "little"))


def uuid_bytes(uuid):
    h = uuid.replace("-", "")
    return " ".join(h[i:i + 2] for i in range(0, 32, 2))


def block(boards):
    q = shlex.quote
    out = [BEGIN,
           "# model profile: everything specific to one model (see boards/*.conf)",
           "# shellcheck disable=SC2034  # board data: not every value is used by this script",
           "model_profile() { # model (from syno_hw_version)",
           '    case "$1" in']
    for b in boards:
        out += [f"    {b['MODEL']})",
                f"        MODEL={q(b['MODEL'])} PLATFORM={q(b['PLATFORM'])} TIER={q(b['TIER'])} BAYS={b['BAYS']}",
                f"        FAT_ID={q(fat_bytes(b['DOM_FAT_ID']))} FAT_ID_TXT={q(b['DOM_FAT_ID'])}",
                f"        EXT_UUID={q(uuid_bytes(b['DOM_EXT_UUID']))}",
                f"        P2UUID={q(b['DOM_EXT_UUID'])}",
                f"        P1_MIN={b['DOM_P1_MIN']} P2_MIN={b['DOM_P2_MIN']}",
                f"        CONSOLE={q(b['CONSOLE'])}",
                "        ;;"]
    out += ["    *) return 1 ;;",
            "    esac",
            "}",
            "# the models of a tier, for messages",
            "models_of_tier() { # tier",
            '    case "$1" in']
    for tier in TIERS:
        names = " ".join(b["MODEL"] for b in boards if b["TIER"] == tier)
        out.append(f"    {tier}) echo {q(names)} ;;")
    out += ["    esac", "}", END]
    return "\n".join(out) + "\n"


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit(__doc__)
    paths = sorted((ROOT / "boards").glob("*.conf"))
    boards = [load(p) for p in paths]
    for p, b in zip(paths, boards):
        want = b["MODEL"].lower().replace("+", "plus")
        if p.stem != want:
            sys.exit(f"{p}: the file of {b['MODEL']} is boards/{want}.conf")
    text = SETUP.read_text()
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", text, re.S)
    if not m:
        sys.exit(f"{SETUP}: no '{BEGIN}' ... '{END}' block")
    new = text[:m.start()] + block(boards) + text[m.end():]
    want = {p.name: p.read_bytes() for p in paths}
    have = {p.name: p.read_bytes() for p in PKG_BOARDS.glob("*.conf")} if PKG_BOARDS.is_dir() else {}
    if check:
        if new != text:
            sys.exit("synodeb-setup.sh is out of date with boards/*.conf: run tools/sync-boards.py")
        if have != want:
            sys.exit(f"{PKG_BOARDS.relative_to(ROOT)} differs from boards/: run tools/sync-boards.py")
        return
    if new != text:
        SETUP.write_text(new)
    PKG_BOARDS.mkdir(parents=True, exist_ok=True)
    for name in set(have) - set(want):
        (PKG_BOARDS / name).unlink()
    for name, data in want.items():
        if have.get(name) != data:
            (PKG_BOARDS / name).write_bytes(data)


if __name__ == "__main__":
    main()
